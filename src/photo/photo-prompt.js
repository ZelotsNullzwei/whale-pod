function extractLook(o = {}) {
  const { framing = {}, outfit = '', hair = '' } = o
  const outfitText = String(outfit ?? '').replace(/\*\*/g, '').replace(/[。；;]+$/, '')
  let hairText = String(hair ?? '').replace(/\*\*/g, '')
  const accMatch = outfitText.match(/(?:白色|蓝色|黑色|粉色)?小?(?:发夹|发卡|发圈|发带)/)
  const accessory = accMatch ? accMatch[0] : ''
  let clothing = (accMatch ? outfitText.replace(accMatch[0], '') : outfitText).replace(/^[，,、\s]+/, '').replace(/[，,、\s]+$/, '')
  /*
   * 2026-11-13 用户定死：**只描述上半身，下半身看不见就不描述**。
   *   · 半身/头肩/面部特写/三分之二身/局部 → 只留上装
   *   · 只有「全身」才保留裤子/裙/袜/鞋
   *   判断只看段首名词（括号里的“塞进裤子”这类说明不算下装）
   */
  if (String(framing?.framing ?? '') !== '全身') {
    clothing = clothing
      .split(/[，,+＋]/)
      .map((s) => s.trim())
      .filter((s) => {
        if (!s) return false
        const head = s.replace(/（[^）]*）|\([^)]*\)/g, '').trim()
        return !/(裤|裙|袜|鞋|拖鞋|靴)/.test(head)
      })
      .join('，')
  }
  /*
   * 2026-11-13 用户：描述越多模型越容易乱 → 统一精简。
   *   去掉括号补充（"下摆塞进裤子"这类），最多保留 3 件主要单品。
   */
  const __isFullBody = String(framing?.framing ?? '') === '全身'
  clothing = clothing
    .split(/[，,]/)
    .map((s) => s.replace(/（[^）]*）|\([^)]*\)/g, '').trim())
    .filter(Boolean)
    // 2026-11-15：**全身不要砍成 3 件**——否则袜/鞋/鲸尾这些排在后面的单品被 slice 丢掉，
    // 女仆装出街就变白袜光脚。只对半身/局部精简到 3 件（反正下半身不入镜）。
    .slice(0, __isFullBody ? 99 : 3)
    .join('，')
  if (accessory) {
    hairText = hairText
      .replace(/(?:戴着|别着|用)?(?:一枚|一个|一只)?(?:白色|蓝色|黑色|粉色)?(?:小)?(?:发夹|发卡|发圈|发带)[^，,；;。]*/g, '')
      .replace(/[，,]\s*只有[^，,；;。]*$/, '')
      .replace(/^[，,、\s]+|[，,、\s]+$/g, '')
  }
  /* 清掉多余标点：连续逗号、行首/行尾逗号、中文逗号后紧跟逗号 */
  clothing = clothing.replace(/[，,]{2,}/g, '，').replace(/^[，,、\s]+|[，,、\s]+$/g, '')
  hairText = hairText.replace(/[，,]{2,}/g, '，').replace(/^[，,、\s]+|[，,、\s]+$/g, '')
  return { clothing, hairText }
}

