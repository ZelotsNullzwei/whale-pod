/**
 * 按当前小时给光线与窗外（2026-11-06 用户：「时间要对的上」）。
 *
 * ⚠️ 之前提示词里**完全没提时间**，凌晨画出来也是"自然光白天"，
 *   和她实际在熬夜对不上。这里按小时给一段明确的描述。
 */
function lightByHour(h = new Date().getHours()) {
  if (h >= 23 || h < 5) {
    return '**深夜**：屋里只开一盏暖黄小灯，光线很暗；窗外是黑的（不要日光、不要白天）；整体偏暗、有轻微噪点'
  }
  if (h < 8) return '**清早**：柔和的晨光从窗外进来，光线偏淡；屋里还没完全亮起来'
  if (h < 11) return '**上午**：明亮柔和的自然光，窗边有光斑'
  if (h < 14) return '**中午**：充足的自然光，稍硬一点'
  if (h < 17) return '**下午**：柔和的斜光，光温偏暖'
  if (h < 19) return '**傍晚**：暖黄的斜阳，光温明显偏暖'
  return '**晚上**：室内暖光为主（顶灯或台灯），窗外已经黑了；不要日光'
}

/** 按拍摄模式隔离姿势。前置/对镜自拍均明确保留一只手的持机职责。 */
const SELFIE_POSES = {
  mirror_selfie: [
    '一只手举手机对着镜子，另一只手自然垂放或轻扶腰，身体微侧',
    '一只手举手机对镜自拍，另一只手轻整理衣角，肩膀自然放松',
    '一只手举手机，手机略遮部分脸，另一只手自然放在身侧',
  ],
  front_selfie: [
    '一只手在画外伸向镜头持手机，另一只手自然垂放',
    '一只手在画外持手机，另一只手轻扶腰，肩膀自然放松',
    '一只手在画外持手机，另一只手轻捏衣角；身体和手臂姿势符合近距离前置自拍',
  ],
  // 普通头肩照不默认假设手机由本人持有。
  portrait: [
    '双手自然放松，可一只手轻整理衣角，不做需要支撑身体的动作',
    '一只手自然垂放，另一只手轻扶腰，肩膀微侧',
    '头部轻微侧转，双手保持自然放松',
  ],
}

function pickSelfiePose(mode) {
  const pool = SELFIE_POSES[mode] || SELFIE_POSES.portrait
  const bucket = Math.floor(Date.now() / (30 * 60_000))
  return pool[bucket % pool.length]
}

