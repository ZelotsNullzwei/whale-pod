/**
 * 提示词组装（photo-prompt）
 *
 * v2.0 方案第六条：把原来的单一模板拆成五个模块，**每个模块只说自己那件事**，
 * 不重复描述同一特征（重复 = 模型被多份描述互相拉扯）。
 *
 *   模块一 人物身份  —— 脸/发/饰品/比例（有参考图时只说"照参考图"）
 *   模块二 生活状态  —— 时间/天气/服装/头发/情绪
 *   模块三 摄影方案  —— 拍摄者/设备/相机位置/角度/构图
 *   模块四 场景与动作 —— 在哪、做什么、手怎么动、视线落哪、周围有什么
 *   模块五 摄影质量  —— 真实手机摄影质感
 * 最后附【禁止】。
 */

import { pairingBlock } from '../memory/outfitRules.js'
import { FACE_CLOSEUP_RULES } from './photo-modes.js'
import { FRAMINGS } from './photo-composer.js'
import { renderExpression } from './photo-expression.js'

/**
 * @param {object} o
 * @param {object} o.plan       已经过 validator 修正的方案
 * @param {object} o.framing    composeFraming 的输出
 * @param {string} o.scene      场景原话（她写的，只当"动作+环境"用）
 * @param {string} [o.outfit]
 * @param {string} [o.hair]
 * @param {string} [o.weather]
 * @param {string} [o.mood]
 * @param {string} [o.continuity] 连续性说明
 * @param {boolean} [o.hasRef]  这次带不带人物参考图
 * @param {boolean} [o.anime]   插画档
 * @param {object} [o.character] { faceRef, bodyRef } 参考图文件名（只用于说明"照哪张"）
 * @returns {string} 完整提示词
 */
/**
 * 按当前小时给光线与窗外（2026-11-06 用户：「时间要对的上」）。
 *
 * ⚠️ 之前提示词里**完全没提时间**，凌晨画出来也是"自然光白天"，
 *   和她实际在熬夜对不上。这里按小时给一段明确的描述。
 */
function lightByHour(h = new Date().getHours()) {
  if (h >= 23 || h < 5) {
    return '**深夜**：屋里只开一盏暖黄小灯，光线很暗；窗外是黑的（不要日光、不要白天）；整体偏暗、有轻微噪点'
  }
  if (h < 8) return '**清早**：柔和的晨光从窗外进来，光线偏淡；屋里还没完全亮起来'
  if (h < 11) return '**上午**：明亮柔和的自然光，窗边有光斑'
  if (h < 14) return '**中午**：充足的自然光，稍硬一点'
  if (h < 17) return '**下午**：柔和的斜光，光温偏暖'
  if (h < 19) return '**傍晚**：暖黄的斜阳，光温明显偏暖'
  return '**晚上**：室内暖光为主（顶灯或台灯），窗外已经黑了；不要日光'
}

export function composePhotoPrompt(o = {}) {
  const {
    plan = {}, framing = {}, scene = '', outfit = '', hair = '', weather = '', mood = '',
    continuity = '', hasRef = false, anime = false, character = {}, expression = null, bodyOverride = '', sceneOnly = false,
    canonRef = false,
  } = o

  const parts = []

  /* ── 模块五（风格先声明，模型最先吃到的调性）──────────────── */
  if (anime) {
    parts.push(`【画风】高质量日系二次元插画：清透柔和的蓝白色调，细腻干净的线稿，
柔和自然的光影，真实布料质感与自然褶皱，避免厚重油腻的厚涂。`)
  } else {
    parts.push(`【画风】真实生活摄影：手机随手拍的自然质感，自然光与真实环境光，
合理的景深与透视，轻微生活噪点；不要插画感、不要3D渲染、不要影棚摆拍感。`)
  }

  /* ── 模块一：人物身份 ─────────────────────────────────────── */
  if (hasRef) {
    /*
     * 有参考图时**只说"照参考图"**：文字重述外貌会覆盖参考图
     * （实测：写"两侧对称两只鳍形耳饰"→ 模型拿这句话重画，脸就变了）。
     */
    const isFullBody = plan.mode !== 'front_selfie' && plan.mode !== 'mirror_selfie'
    const which = '参考图'
    /*
     * ⚠️ 睡衣/睡觉场景**不戴头饰**（2026-11-06 实测）：
     *   白名单写了「不戴头饰」，但这里把女仆头饰当身份特征写死，压过了服装描述。
     */
    /*
     * ★★ **头饰跟着衣服走**（2026-11-07 实测事故）：
     *   今天穿的是「宽松过臀大 T 恤当睡裙、光腿白棉袜」，
     *   但提示词把「白色蕾丝女仆头饰」当身份特征写死 → 生成图里
     *   她穿着 T 恤、头上却顶着女仆蕾丝头饰 + 鲸鱼耳鳍，特别出戏。
     *
     *   规则：先看这套衣服自己写没写头饰；写了就照它，
     *        是女仆装才给女仆头饰；**什么都没写就默认不戴**。
     */
    const headwear = (() => {
      const o = String(outfit ?? '')
      if (/不戴头饰/.test(o)) return '**头上不戴任何头饰**（没有发带、没有蕾丝帽子、没有蝴蝶结），但下面这条一定要有；'
      if (/女仆/.test(o)) return '白色蕾丝女仆头饰；'
      const m = o.match(/(白色蕾丝头带|蕾丝发带|发带|发圈|马尾|发夹|夹子|蝴蝶结头饰|头饰)[^，,；;。]*/)
      if (m) return `${m[0]}；`
      return '**头上不戴任何头饰**（没有发带、没有蕾丝帽子、没有蝴蝶结），但下面这条一定要有；'
    })()
    parts.push(`【人物】保持${which}里**这个人${isFullBody ? '的脸和身形' : '的头部特征'}完全不变**：
脸型与五官比例、眼睛颜色、蓝色长卷发与齐刘海、头顶正中那缕呆毛、
${headwear}
⚠️ **不戴头饰 ≠ 不戴耳鳍**：头上可以什么都没有，但**耳侧那对深蓝配白的鲸鱼鳍形耳饰每一张都必须在**
（不是猫耳、不是发卡、不是蝴蝶结，就是贴在耳侧向外张开的鳍形薄片）—— 这是她唯一的识别标志。
身形比例也照参考图：身高 165cm、头身比 7.8、肩宽 33cm（窄肩薄背、自然斜肩）、
${bodyOverride ? `${bodyOverride}、` : ''}
**身形是有曲线但克制的少女体型**（不是平板，也不是夸张的沙漏型）：
- 胸 82cm（**B 罩杯，偏小的那一头**）：隔着衣服是**平缓的弧线** ——
  正面对镜几乎看不出起伏，侧面也只有一点点曲线；不要事业线、不要强调体积。
- ⚠️ **所有照片里这个大小必须完全一致**（2026-11-06 用户：两张图胸不一样大，
  一张显大一张显小）。**不许**因为衣服松紧、姿势、镜头远近、道具遮挡而变大变小 ——
  这一条比"显身材/有曲线"优先。
- **左右必须对称**：两边大小一致、高低齐平、形状相同。
  ⚠️ 另外也出现过**一大一小、一边垂一边挺**：不要一大一小、不要一高一低、不要单侧下垂；
  双臂动作（比如一只手举手机）也**不许把胸型带歪**。
- 腰 58cm：**细**，腰线明显，侧面看是收进去的。
- 臀 85cm：**窄胯但有形状** —— 侧面看臀线清楚、微微上翘，**不是平的、也不是宽胯**。
- 上臂围 21cm、手腕 13cm、腿细直不 O 型。
⚠️ 侧面/斜侧角度时**腰要收进去**就够 —— 不要为了"曲线"去加胸围或胯宽。
⚠️ 不要夸张（大胸、宽胯都不对）；也不要画成完全平板 —— 就按上面这句"平缓的 B"来。
⚠️ **不用刻意处理事业线**：宽松衣服没有束缚，看不到事业线是正常的；
   有内衣托着时才会有。按衣服的实际松紧自然呈现，别硬加也别硬删。
**不要重新设计人物，也不要照搬参考图里的姿势和背景。**`)
    /*
     * ★★ **定妆照**（2026-11-06 A 方案）。
     *   这张参考图就是这套衣服的"标准像"，只对齐款式/体型/尾巴数量。
     */
    if (canonRef) {
      parts.push(`【参考图是这套衣服的定妆照】
- **只对齐这三件事**：① 这套衣服的款式（领口、袖子、围裙、裙摆层次与蕾丝、袜子、鞋、发饰）；
  ② 体型三围（和参考图同一副身材，不许更丰满或更瘦）；③ **尾巴只有一条**（位置、大小照参考图）。
- **不要**照搬参考图的姿势、构图、背景、光线、手机位置 —— 这些按【摄影方案】来。
- 不许换款式、不许加装饰（刺绣、蕾丝、扣子都要和参考图一致）。`)
    }
  } else if (plan.needsCharacterRef === false) {
    /*
     * ⚠️ **场景图（sceneOnly）不许出现人**（2026-11-06 实测）：
     *   原来写"只出现手/手臂/腿，或一缕头发"，模型直接画了后脑+肩膀 → 第三人称。
     */
    if (sceneOnly) {
      parts.push(`【人物】**画面里没有人** —— 这张只拍东西/环境（桌面、窗外、玻璃、物品）。
⚠️ 不要出现她的脸、头发、后脑、肩膀、手臂、腿、脚，也不要出现她的身影或倒影。`)
    } else {
      parts.push(`【人物】她本人基本不在画面里（只出现手/手臂/腿）。
⚠️ 入画的那部分**必须是同一个人**：
- 皮肤：偏白、真实质感（不是塑料感）；
- 手：手指修长、指节清楚，指甲短而平整（不涂甲油）；
- 腿：纤细、直，不是 O 型。`)
    }
    /*
     * ⚠️ 即使人不在画面，**入画的那部分也必须是她的**（2026-11-06 用户指正）：
     *   原来只写"手指修长"，模型就把头发画成黑发/棕发（发色不对）。
     */
    parts.push(`【人物】她本人基本不在画面里（只出现手/手臂/腿，或一缕头发）。
⚠️ 入画的那部分**必须是同一个人**：
- 皮肤：偏白、真实质感（不是塑料感）；
- 手：手指修长、指节清楚，指甲短而平整（不涂甲油）；
- 腿：纤细、直，不是 O 型；
- 如果有一缕头发/发丝入画：**蓝色长卷发**（发根深蓝渐变到发梢浅蓝）——
  **绝不是黑发、棕发或金色**。`)
  } else {
    /* 没有参考图（异常情况）：退回文字描述，至少别画成路人 */
    parts.push(`【人物】十八九岁的中国女孩子：脸型柔和、下颌线清楚（不要法令纹、不要眼袋）；
棕色瞳孔；**蓝色长卷发**（发根深蓝渐变到浅蓝、齐刘海、头顶一缕呆毛、过腰）；
白色蕾丝女仆头饰（一侧蓝蝴蝶结）；耳侧各一组深蓝配白的鳍形装饰（戴上去的饰品，不是长出来的鳍）。
身高 165cm、头身比 7.8、窄肩薄背、四肢纤细、腿直。`)
  }

  /* ── 模块二：生活状态 ─────────────────────────────────────── */
  const life = []
  if (weather) life.push(`天气：${weather}`)
  if (mood) life.push(`心情：${mood}`)
  /*
   * ⚠️ **第一人称不写衣服、不写头发**（2026-11-06 全量实测）：
   *   写了「今天穿着…」「今天的头发…」模型就理解成"要画这个人"，
   *   连出两张都是侧脸 + 后脑 + 肩膀。第一人称只看得到手和眼前的桌面。
   */
  const fpOnly = plan.mode === 'first_person'
  /*
   * ★ 第一人称不写"从头发到鞋跟"（2026-11-05）：
   *   那句会让模型把整个人画出来 —— 第一人称只看得到手和眼前的东西。
   */
  if (outfit && !fpOnly) {
    life.push(`今天穿着：${outfit}（服装完全按这句，从头发到鞋跟，不要另设计）`)
    /*
     * ★★ **款式锁死**（2026-11-06 用户：「款式不统一」）。
     *
     * 现场：同一套短款女仆装，三张图三个样 ——
     *   领口有时是方领、有时是 V 领；围裙有时带肩带、有时没有；
     *   袜子有时纯白、有时带蕾丝边。用户的原话是「款式不统一」。
     *
     * 原因是上面那行只是"散文描述"，模型每次都会**重新设计一遍**。
     * 这里把部件拆成清单，要求逐件对得上、且跨图一致。
     */
    life.push(`**这套衣服是固定设定，不是每次重新设计** —— 下面每个部件**必须逐件对得上**：
- 逐字照上面那句，不许增删部件、不许换款式、不许改配色明暗；
- 领口形状、袖子长度与样式、围裙（有无肩带/刺绣位置）、裙摆层数与蕾丝边、
  袜子（颜色/长度/有无蕾丝袜口）、鞋、发饰 —— 每一样都必须是**同一个设计**；
- 同一套衣服在**每一张照片里看起来都必须是同一件**（不能这张泡泡袖、下张无袖）。`)

    /*
     * ★★ **衣着以这一行为准**（2026-11-06 实测）。
     *
     * 现场：她写 `[画图:对镜自拍，穿着藏青连身短款女仆装和白蕾丝围裙，裙摆很短…]`
     * —— 这句里**没有过膝白丝**；而「今天穿着」那行是衣柜原文，有。
     * 两段描述同时进提示词，模型跟着**场景那句**走 → 画出来光腿。
     *
     * 所以明确一句：场景里提到的衣着**不算数**。
     */
    life.push('⚠️ 衣着**只按上面「今天穿着」那一行**；下面的场景描述里如果也写了衣服/袜子/鞋，'
      + '那是她自己随口概括的，**忽略它**，别按它改（否则会漏掉袜子和鞋）。')
  }
  if (hair && !fpOnly) life.push(`今天的头发：${hair}`)
  if (life.length) parts.push(`【生活状态】\n${life.join('\n')}`)
  /*
   * ★ 搭配要成立（2026-11-06，来自 B 站半裙搭配 + 知乎 7 个技巧）：
   *   模型不会自己想搭配 —— 不管它就画成上下都宽、三段分色、长裙配高帮靴。
   *   只在**有人入画**时加（第一人称/纯场景用不上）。
   */
  if (plan.needsCharacterRef !== false && !fpOnly) {
    const pb = pairingBlock(outfit)
    if (pb) parts.push(pb)
  }

  /* ── 模块三：摄影方案（这是 v2.0 的核心）─────────────────── */
  /*
   * ★ 面部特写：三条冲突规则都要让路（见 patch 注释）。
   *   实测不处理的话，脸会低下去、构图变成三分之二身。
   */
  const isCloseup = framing.framing === '面部特写'
  const shot = [
    `拍摄者：${plan.shooter}`,
    `设备：${plan.device}`,
    `相机位置：${plan.camera}`,
    `视角高度：${framing.cameraAngle ?? '平视'}`,
    `构图：${framing.desc ?? '半身'}`,
    `视线：${isCloseup ? '**直视镜头**，眼神落在镜头上（不许看屏幕、不许往下看）' : plan.look}`,
  ]
  if (plan.hidePhone) shot.push('手机不出现（不要画出手机）')
  parts.push(`【摄影方案】
${shot.join('\n')}
${(plan.rules ?? []).filter((r) => !isCloseup || !/(别瞪着镜头|别把脸怼满屏|多留白)/.test(r)).map((r) => '- ' + r).join('\n')}
${(framing.notes ?? []).map((n) => '- ' + n).join('\n')}
⚠️ **线上陪伴关系**：她在自己家、用**自己的手机**拍，然后发到 QQ 上。
- **不要虚构现实中的朋友、家人或摄影师**，画面里只有她一个人。
- **不要假设他在她身边**，也不要生成"从他的视角"拍的照片。
- 他说"帮你拍/我给你拍"也不代表见面 —— 她只能自拍、对镜拍、架机拍。
- 要看她的样子，就靠**前置自拍 / 镜子自拍 / 视频通话**这三条路，不靠第三个人。`)

  /*
   * ★ 面部特写 / 头肩：眼睛必须看镜头（2026-11-06 用户要求）。
   *   SELFIE_RULES 那条「别瞪着镜头、可以略微看向旁边」会把特写的视线带跑，
   *   这里用一条更硬的规则覆盖它。
   */
  if (framing.framing === '面部特写') {
    parts.push(['【面部特写（怼脸）】', ...FACE_CLOSEUP_RULES.map((r) => '- ' + r)].join('\n'))
  } else if (framing.framing === '头肩') {
    parts.push('【眼神】**眼睛直视镜头** —— 眼神落在镜头上，不要飘到一边、不要半闭、不要斜视。')
  }

  /*
   * ★ **部位特写**（2026-11-07 用户：「看看脚，看看手，看看腿，
   *   看看小肚子，看看胸一类的」）。
   *
   * 这种图的关键是"只拍那一块"：不写死，模型一定把整个人画进来
   * （它默认"人物照就该有脸"）。所以单独一段，明确"脸在画外"。
   */
  if (framing.bodyPart) {
    parts.push(`【部位特写：只拍${framing.bodyPart}（自拍，手机在她自己手里）】
- 画面**只框住${framing.bodyPart}**，其余身体全在画外 —— **不出现脸、不出现全身、不出现整间屋子**。
- 手机在她手上：最多**一条胳膊从画面边缘伸进来**（拿手机的那条）；
  **不要出现第二只手**、不要让手机悬空、不要"第三只手"。
- 镜头贴得很近（30~50cm），俯拍或平视；像随手抬起手机就拍，不是影棚摆拍。
- ${framing.bodyPart}的肤色、质感、指甲、衣着部件，跟人物设定和当天穿搭一致；只露该露的那一部分。
- 不要拼贴、不要"一格里两个视角"、不要在角落补一张小图；不要影棚打光、不要过度磨皮。`)
  }

  /*
   * ★ 连身睡裙要看得见裙摆（2026-11-06 实测）：
   *   被子盖住下半身时模型只剩上衣可画，补了个短裤 → 睡裙变 T 恤+短裤。
   */
  /*
   * ★ 尾巴**只有一条**（2026-11-06 实测）：
   *   写「双叶尾鳍」被画成左右各一条，必须明说是一条、末端分两片。
   */
  if (/尾巴/.test(String(outfit ?? ''))) {
    parts.push(`⚠️ 她身后**只有一条**鲸鱼尾巴：从腰后正中伸出，末端分成左右两片叶状尾鳍。
    **不是左右各一条、不是两条**。
⚠️ 再具体一点（2026-11-06 实测又画成两条）：整张图里**只能有一个尾巴根部**
（腰后正中那一处），**只能有一条尾柄**，末端那两片鳍是**同一条尾巴的分叉**。
不许在腿边、裙侧、身后再长出第二个尾巴或第二对鳍；
镜子里看到的也必须是**同一条**（不是镜像出第二条）。`)
  }

  if (/连身.*睡裙/.test(String(outfit ?? ''))) {
    parts.push(`⚠️ 她穿的是**一件式连身睡裙**（下摆到膝），被子只盖到腿上，
    **上半身和裙摆都要看得见**（被子只盖到腿以下）；这是睡衣，不是日常 T 恤。`)
  }

  /* ── 模块四·五：表情与肢体（2026-11-05 加）────────────────── */
  if (expression && expression.face) {
    parts.push(renderExpression(expression))
  }

  /*
   * ★ 洗掉"拍摄设备"那半句（2026-11-05 实测三次翻车）：
   *   用户说「手机架在茶几上」→ 这句原样进了提示词 → 模型把手机画出来。
   *   写禁令反而更明显（否定式提示词会召唤物体）。
   *   做法：**按逗号切段，丢掉含设备词的段**，只留"她在做什么 + 环境"。
   */
  const sceneClean = (() => {
    const raw = String(scene ?? '')
    const DEVICE = /(手机|相机|平板|支架|三脚架|自拍杆|定时拍|定时摄影|拍摄中)/
    const kept = raw.split(/[，,。；;]/).map((x) => x.trim()).filter((x) => x && !DEVICE.test(x))
    const out = kept.join('，').trim()
    return out || raw
  })()
  /* ── 模块四：场景与动作 ───────────────────────────────────── */
  /*
   * ⚠️ 场景原话**只当"动作+环境"用**：
   * 她经常在场景里写外貌（"蓝黑色长发""只露侧脸"），那会覆盖参考图。
   */
  if (plan.mode === 'first_person') {
    /*
     * ★ 入画的腿脚也要有衣服（2026-11-06 实测）：
     *   上一轮把衣服全删了 → 腿入画时变成光腿（本来是长裤）。
     *   这里只写**入画的那几件**（裤/袜/拖鞋），不写上衣 —— 避免召唤整个人。
     */
    const visibleCloth = String(outfit ?? '')
      // 先去括号内容 —— 否则"衬衫（不扎进裤子）"会因为提到"裤子"被误选
      .replace(/（[^）]*）/g, '')
      .split(/[，,]/).map((x) => x.trim())
      .filter((x) => /裤|袜|拖鞋|鞋|脚/.test(x))
      .join('，')
    /*
     * ★ 第一人称：镜头就是她的眼睛 —— 画面里不能有"她整个人"。
     *   实测：场景写「她坐在床边吃饭」，模型就画了第三人称全身照。
     */
    parts.push(`【画面】第一人称：镜头就是她的眼睛，看到的是**她眼前的东西**。
⚠️ **画面里绝对不能出现**：她的脸、侧脸、后脑、头发、肩膀、脖子、上半身 ——
  这一张是**低头看**的视角，镜头朝下对着手和眼前的桌面，不是"从旁边看她"。
场景内容：${sceneClean}
${continuity ? '\n' + continuity : ''}
${lightByHour()}
⚠️ **硬性要求（第一人称）**：
- **画面里不能出现她整个人、也不能出现她的脸** —— 镜头在她眼睛位置，看不到自己。
- 只能出现：**她的手/手臂**（做动作的那部分）、眼前的桌面/食物/物件、房间的一角。
- **不要第三人称视角**（不是别人在旁边拍她）。
- ⚠️⚠️ **和镜子自拍 / 自拍 / 视频通话不要混用**（2026-11-07 实测事故）：
  这一张**没有镜子**：不要出现镜子边框、不要出现"镜子里映出她"、不要把手机举在她面前。
  镜头就在她眼睛上，她**看不见自己**，所以画面里也不该出现"某个人的手机屏幕对着她"。
- 场景里写「她坐着/她在吃」→ 理解成**她的手在做什么**，不要把人画进画面。
- **最多两只手**：画面里出现的手/手臂加起来不超过 2 只，不许从画面边缘伸进来第三只。
${visibleCloth ? `\n她入画的腿脚穿着：${visibleCloth}（只画裤腿、袜脚、拖鞋；不要画上半身，也不要画脸）` : ''}
⚠️ 场景里如果出现描写她**外貌**的词，一律作废、不要照画。`)
  } else {
    parts.push(`【画面】只管"她在做什么 + 周围有什么 + 光线氛围"
${sceneClean}
${continuity ? '\n' + continuity : ''}
${lightByHour()}
⚠️ 上面这句里如果出现描写她**外貌**的词（发色、发型、头饰、首饰、"蓝黑色长发""只露侧脸"之类），
**一律作废、不要照画** —— 长相/发色/头饰/耳饰以参考图和【人物】为准。`)
  }

  /* ── 禁止 ───────────────────────────────────────────────── */
  const bans = [
    '第三个人 / 现实中的朋友 / 摄影师（她是独居线上陪伴，画面里只有她）',
    '多余手指、畸形手掌、重复肢体',
    ...(plan.mode === 'first_person'
      ? ['第二个人（画面里出现别人的手/手臂/身体）', '镜子、镜面反射（这一张没有镜子）']
      : []),
    '水印、文字、界面截图',
    '二次元/Q版/低龄化（写实档）',
    '拼贴感：头像贴到另一个身体上、双重打光、局部清晰度不一致',
    '胸型不对称（一大一小 / 一高一低 / 单侧下垂）',
    '款式漂移：同一套衣服换个领口、换个袖子、围裙少个部件（每张都必须是同一件）',
  ]
  if (plan.mode !== 'mirror_selfie') bans.push('镜面反射（这一张没有镜子）')

  if (plan.hidePhone) bans.push('手机')
  if (plan.needsCharacterRef === false) bans.push('她自己的完整脸部')
  // 部位特写如果是「脚」，这条禁令必须让路（否则自己把自己禁掉）
  if (!framing.feet && framing.bodyPart !== '脚') bans.push('完整双脚（这一张不拍脚）')
  parts.push(`【禁止】\n${bans.map((b) => '- ' + b).join('\n')}`)

  parts.push(`【输出】竖版 9:16，单张。`)

  return parts.join('\n\n')
}
