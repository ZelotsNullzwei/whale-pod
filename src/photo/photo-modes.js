/** 按 id 取模式；未知 id 返回 null（调用方要处理） */
export function getMode(id) {
  return MODES[String(id ?? '')] ?? null
}

/** 这个模式能不能让脸出现在画面里 */
export function modeShowsFace(id) {
  return id === 'front_selfie' || id === 'mirror_selfie' || id === 'video_call'
}

/** 这个模式是不是"主体是人"（决定要不要带人物参考图） */
export function modeNeedsCharacterRef(id) {
  return id !== 'first_person' && id !== 'rear_selfie'
}
