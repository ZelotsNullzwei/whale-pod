/**
 * 「车牌」识别 —— 群友/私聊里用**代号**指某部作品，而不是发链接。
 *
 * ## 为什么需要
 * 实测（2026-11-02）：`JM123456` 这种编号会被 `needsFreshInfo` 当成
 * **"提到具体名字"** → 拿去**联网搜索**，而且搜的是**原始字符串**
 * （「看看这个 JM123456」就搜整句）→ 基本是垃圾结果，还白花钱。
 *
 * 而纯数字（`421234`）或「禁漫 123456」这种写法**连搜都不触发** ——
 * 于是她**完全没反应**，用户看到的就是"她看不懂"。
 *
 * ## 这里只做「认出来 + 说清楚」，不做「去抓」
 * 认出编号之后，把「这是什么」写进提示词，让模型**知道自己在看什么**：
 *   · 不会再当乱码
 *   · 不会拿它去搜索（那是 C 那条，见 bridge.js 的搜索闸）
 *   · 也不会**装看过**（"我看不到内容"这句必须留着）
 *
 * ⚠️ **刻意不生成站点 URL**。原因有两条：
 *   ① 这些站（尤其成人站）域名一直在换，写死必然过期；
 *   ② 写个 URL 出来，`link-preview` 那条路就会**真去连** ——
 *      那是要单独决策的事（成人内容 + 反爬），不该顺带做掉。
 *
 * ## 加新编号
 * 往 `PATTERNS` 里加一条就行。**只加"有稳定前缀"的** ——
 * 纯数字那种太容易误伤（房间号、订单号、股价、手机号后四位…）。
 */

/**
 * @typedef {{kind:string, id:string, label:string, raw:string}} DetectedCode
 */

/** 已知的编号形态。`re` 里**必须**有一个捕获组给出编号。 */
const PATTERNS = [
  /*
   * ★★★ **链接形态**（2026-11-03 加）—— 这是**最自然的发法**，原来却没认 ✗。
   *
   * 现场：用户在私聊里发 `https://18comic.vip/album/1481228`，
   * 她回「**我这边打不开，链接是死的**」—— 因为 `detectCode` 返回 null，
   * 那条消息就**普通链接预览**那条路走了（成人站预览必然失败 ✗），
   * 而**能真看内页的 `jm-read` 一次都没触发过**。
   *
   * 实测（加之前）：
   * ```
   * 「JM1481228」                       → ✅ 认
   * 「https://18comic.vip/album/1481228」→ ✗ null   ← 用户真发的就是这个
   * 「https://18comic.ink/album/…」      → ✗ null
   * 「18comic.vip/album/1481228」        → ✗ null
   * ```
   *
   * ⚠️ **不硬编码域名列表**（上面那条注释说得对：域名一直在换）——
   *    只认域名里的 **`18comic` 这个商标名**，TLD 随意；路径认 `/album/<数字>`。
   *    商标名不会换，TLD 才换 —— 这样既不写死、又能认全。
   */
  {
    kind: 'jm',
    label: '禁漫（18comic）的作品编号',
    re: /18comic\.[a-z]+(?::\d+)?\/(?:[a-z-]+\/)*album\/(\d{4,8})/i,
  },
  {
    kind: 'jm',
    label: '禁漫（18comic）的作品编号',
    // JM123456 / jm 123456 —— 前缀大小写都认，中间允许空格
    re: /\b[Jj][Mm]\s*(\d{4,8})\b/,
  },
  {
    kind: 'jm',
    label: '禁漫（18comic）的作品编号',
    /*
     * 「禁漫 123456」/「禁漫123456」—— 中文词有辨识度，够稳。
     * ⚠️ 放最后：前面两条更明确。**纯数字仍然不认**（注释里那条规矩是对的：
     *    房间号、订单号、股价、手机号后四位都会误伤）。
     */
    re: /禁漫\s*[:：]?\s*(\d{4,8})/,
  },
]

/**
 * 从消息里认出「车牌」。
 *
 * @param {string} text
 * @returns {DetectedCode|null}
 */
export function detectCode(text) {
  const s = String(text ?? '')
  if (!s) return null
  for (const p of PATTERNS) {
    const m = p.re.exec(s)
    if (!m) continue
    return { kind: p.kind, id: m[1], label: p.label, raw: m[0].trim() }
  }
  return null
}

/**
 * 把认出来的编号变成**喂给模型的注记**。
 *
 * ## 这个函数存在的意义就是"防编"
 * 它只在**什么都还没拿到**的时候用（抓标题/看内页那两条路都失败/还没跑完）。
 * 所以措辞必须**说清手里是空的**，而且要把话堵死。
 *
 * ## ★★ 2026-11-02 实测被绕过一次，所以加强了
 * 群里追问「看完没」，她回：
 * ```
 * 「没看完，**就扫了眼标题**。本鱼说一眼就是一眼，没骗你。」
 * ```
 * **而标题根本没抓到**（所有域名都失败了）。
 *
 * ⚠️ 老措辞（「我看不到里面的内容」）拦不住它，原因很细：
 *    这句只否定了"**里面**"（内页），**没否定标题** ——
 *    于是"扫了眼标题"在它看来**不算撒谎**，还顺手把上一轮的话圆上了。
 *
 * 所以现在：**逐项说明手里有什么**（标题没有、画面没有），
 * 并把「扫了眼标题」这种中间状态**点名堵死**。
 * 编造里最阴的不是"编内容"，是**虚报"我看过"** —— 因为它读起来毫无破绽。
 *
 * @param {DetectedCode} code
 */
export function formatCodeContext(code) {
  return `〔提示：\`${code.raw}\` 是${code.label}（编号 ${code.id}）。\n`
    + '**我这次什么都没拿到**：标题没抓到、内页也没打开。\n'
    + '所以只能说"这个号我打不开 / 我看不了"。\n'
    + '⚠️ **不许说"我扫了眼标题""我瞅了一眼"这类话** —— 标题我也没拿到，说了就是假的。\n'
    + '⚠️ **也不许猜它讲了什么**。他追问"看完没"，就直说没看成。〕'
}