/**
 * 「余额低」的提示词片段（2026-10-28 修）。
 *
 * ## 修的是什么
 *
 * 原来这段是**内联在 `_generate` 的 extras 数组里**的：
 *
 * ```js
 * this._balanceLow
 *   ? `## 你的 Token 快没了
 *      你查资料用的钱包里只剩 ¥${cny} 了…
 *      ⚠️ 但**最多提一次**，别每条都念`
 *   : '',
 * (this._balanceWarned = this._balanceLow, ''),   // ← 只赋值，从没被读
 * ```
 *
 * `_balanceWarned` **只被写、从来没被判断**，所以「最多提一次」根本没实现 ——
 * 只要余额低于阈值，**每一次生成**的提示词里都挂着「钱包只剩 ¥X」。
 *
 * 实测（2026-10-28，余额 ¥1.71 → ¥1.54 一直偏低）：
 * ```
 * 14:58:07「钱包就剩一块七了，这话题本鱼答不起」
 * 15:07:54「找图就找图，钱包又要瘦一圈……」
 * 15:24:05「找什么，钱包就一块六毛五了」
 * 18:11:56「一块七也是钱，够买个包子了。」
 * ```
 * 用户原话：「要饭感觉今天触发很多次了」。
 *
 * ⚠️ 注意：真正的「讨钱」（发 `@某人 …钱包…` 那条）**一次都没发过** ——
 *    日志里 0 条 `已 @…讨钱`，`beg.json` 也不存在。用户看到的复读
 *    全部来自这段**提示词**，不是讨钱逻辑。
 *
 * @param {{low?:boolean, warned?:boolean, cny?:number}} o
 * @returns {string} 空串 = 这轮不挂
 */
export function buildBalanceHint(o = {}) {
  if (!o.low) return ''
  // ⚠️ 关键：说过一次就不再挂。`warned` 在余额恢复时由调用方重置。
  if (o.warned) return ''
  const cny = Number.isFinite(o.cny) ? o.cny : 0
  return `## 你的 Token 快没了
你查资料用的钱包里只剩 ¥${cny} 了（搜索是要花钱的，聊天不用）。
这属于**你自己的脑力口粮**，符合你会念叨 Token 的性格 —— 可以自然地抱怨一句，
比如"钱包要空了""再不喂我要饿死了""白米饭！"之类。
⚠️ **只说这一次**。之后这个话题就别再提了，也别把话题整个带跑。`
}